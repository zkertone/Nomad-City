assert.equal(facilities.FOUNDERS_FACILITY_COLOR_CONFIRMATIONS[0].color, 'rainbow');
assert.equal(Object.hasOwn(facilities.FOUNDERS_FACILITY_COLOR_CONFIRMATIONS[0], 'colorCellCount'), false);
assert.equal(facilities.getConfirmedFacilityCopyCount('物流枢纽'), 2);
const changed = JSON.parse(JSON.stringify(catalog)); changed.facilities[0].copyCountsByColor.red = 2;
changed.contentHash = facilities.computeFacilityColorCountsHash(changed);
assert.equal(facilities.validateFoundersFacilityColorCounts(changed).success, false);
assert.throws(() => facilities.getFoundersFacilityColorCountRecord('constructor'), RangeError);
const counts = { red: 0, blue: 0, yellow: 0, rainbow: 0 };
for (const facility of catalog.facilities) for (const color of Object.keys(counts)) counts[color] += facility.copyCountsByColor[color];
assert.deepEqual(counts, { red: 13, blue: 13, yellow: 13, rainbow: 14 });
console.log(JSON.stringify({ colorRecords: 20, reportedCopiesByColorExcludingTower: counts, contentHash: catalog.contentHash, coreCommandTowerCards: 4, inventory: facilities.getFacilityInventoryReconciliation() }));
console.log('PASS: compiled root/facilities exports, faithful reported quantities, base-only filtering and confirmed enterprise/Infected editions and tamper rejection');

