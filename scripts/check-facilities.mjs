import assert from 'node:assert/strict';
import * as core from '@nomad-city-online/game-core';
import * as facilities from '@nomad-city-online/game-core/facilities';
assert.equal(core.FOUNDERS_FACILITY_COLOR_COUNTS, facilities.FOUNDERS_FACILITY_COLOR_COUNTS);
assert.equal(core.getConfirmedFacilityCopyCount, facilities.getConfirmedFacilityCopyCount);
const catalog = facilities.FOUNDERS_FACILITY_COLOR_COUNTS;
assert.equal(catalog.verificationStatus, 'user-confirmed-colors-only'); assert.equal(catalog.facilities.length, 20);
assert.equal(facilities.validateFoundersFacilityColorCounts(catalog).success, true);
assert.deepEqual(facilities.getFoundersFacilityColorCountRecord('FAC-018').colorCellCounts, { red: 1, blue: 1, yellow: 1, rainbow: 0 });
assert.deepEqual(facilities.getFoundersFacilityColorCountRecord('FAC-016').colorCellCounts, { red: 0, blue: 0, yellow: 0, rainbow: 2 });
assert.equal(facilities.getConfirmedFacilityCopyCount('核心指挥塔'), 4);
assert.equal(facilities.getConfirmedFacilityCopyCount('物流枢纽'), null);
const changed = JSON.parse(JSON.stringify(catalog)); changed.facilities[0].colorCellCounts.red = 2;
changed.contentHash = facilities.computeFacilityColorCountsHash(changed);
assert.equal(facilities.validateFoundersFacilityColorCounts(changed).success, false);
assert.throws(() => facilities.getFoundersFacilityColorCountRecord('constructor'), RangeError);
const counts = { red: 0, blue: 0, yellow: 0, rainbow: 0 };
for (const facility of catalog.facilities) for (const color of Object.keys(counts)) counts[color] += facility.colorCellCounts[color];
assert.deepEqual(counts, { red: 13, blue: 13, yellow: 13, rainbow: 14 });
console.log(JSON.stringify({ colorRecords: 20, cellsByColor: counts, contentHash: catalog.contentHash, coreCommandTowerCards: 4, otherCopyCounts: 'unknown' }));
console.log('PASS: compiled root/facilities exports, exact confirmed counts, separate inventory fact and pinned tamper rejection');
