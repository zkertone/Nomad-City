import assert from 'node:assert/strict';
import * as core from '@nomad-city-online/game-core';
import * as facilities from '@nomad-city-online/game-core/facilities';
assert.equal(core.FOUNDERS_FACILITY_COLOR_COUNTS, facilities.FOUNDERS_FACILITY_COLOR_COUNTS);
assert.equal(core.getConfirmedFacilityCopyCount, facilities.getConfirmedFacilityCopyCount);
const catalog = facilities.FOUNDERS_FACILITY_COLOR_COUNTS;
assert.equal(catalog.verificationStatus, 'user-confirmed-copy-counts-and-editions'); assert.equal(catalog.facilities.length, 20);
assert.equal(facilities.validateFoundersFacilityColorCounts(catalog).success, true);
assert.deepEqual(facilities.getFoundersFacilityColorCountRecord('FAC-018').copyCountsByColor, { red: 1, blue: 1, yellow: 1, rainbow: 0 });
assert.deepEqual(facilities.getFoundersFacilityColorCountRecord('FAC-016').copyCountsByColor, { red: 0, blue: 0, yellow: 0, rainbow: 2 });
assert.equal(facilities.getConfirmedFacilityCopyCount('核心指挥塔'), 4);
assert.equal(facilities.FOUNDERS_FACILITY_COLOR_CONFIRMATIONS[0].color, 'rainbow');
assert.equal(Object.hasOwn(facilities.FOUNDERS_FACILITY_COLOR_CONFIRMATIONS[0], 'colorCellCount'), false);
assert.equal(facilities.getConfirmedFacilityCopyCount('物流枢纽'), 2);
const changed = JSON.parse(JSON.stringify(catalog)); changed.facilities[0].copyCountsByColor.red = 2;
changed.contentHash = facilities.computeFacilityColorCountsHash(changed);
assert.equal(facilities.validateFoundersFacilityColorCounts(changed).success, false);
assert.throws(() => facilities.getFoundersFacilityColorCountRecord('constructor'), RangeError);
const counts = { red: 0, blue: 0, yellow: 0, rainbow: 0 };
for (const facility of catalog.facilities) for (const color of Object.keys(counts)) counts[color] += facility.copyCountsByColor[color];
assert.deepEqual(counts, { red: 13, blue: 13, yellow: 13, rainbow: 14 });
console.log(JSON.stringify({ colorRecords: 20, reportedCopiesByColorExcludingTower: counts, contentHash: catalog.contentHash, coreCommandTowerCards: 4, inventory: facilities.getFacilityInventoryReconciliation() }));
console.log('PASS: compiled root/facilities exports, faithful reported quantities, base-only filtering and confirmed enterprise/Infected editions and tamper rejection');

const inventory = facilities.getFacilityInventoryReconciliation();
assert.deepEqual(inventory.reported, { base: 48, enterprise: 3, infected: 6, total: 57 });
assert.deepEqual(inventory.baseBreakdown, { ordinary: 41, coreCommandTower: 4, extensionHub: 3 });
assert.equal(inventory.totalsReconciled, true); assert.equal(inventory.readyForDeckSetup, false);
assert.equal(facilities.getFacilityCopyCountRecords().some(record => record.edition !== 'base'), false);
assert.equal(facilities.getFacilityCopyCountRecords().length, 18);

assert.equal(core.FOUNDERS_FACILITY_FACES, facilities.FOUNDERS_FACILITY_FACES);
assert.equal(core.getFoundersFacilityFace, facilities.getFoundersFacilityFace);
assert.equal(facilities.validateFoundersFacilityFaces(facilities.FOUNDERS_FACILITY_FACES).success, true);
assert.equal(facilities.getFoundersFacilityFace('FAC-018').printedScore, -1);
assert.deepEqual(facilities.getFoundersFacilityFace('FAC-CORE-COMMAND-TOWER').constructionCost, { kind: 'not-printed' });
assert.throws(() => facilities.getFoundersFacilityFace('FAC-020'), RangeError);
const faces = JSON.parse(JSON.stringify(facilities.FOUNDERS_FACILITY_FACES));
faces.facilities[0].printedScore++;
faces.contentHash = facilities.computeFacilityFacesHash(faces);
assert.equal(facilities.validateFoundersFacilityFaces(faces).success, false);
assert.equal(facilities.getFacilityInventoryReconciliation().readyForDeckSetup, false);
console.log(JSON.stringify({ faceTranscription: facilities.getFacilityFaceTranscriptionProgress(), faceContentHash: facilities.FOUNDERS_FACILITY_FACES.contentHash }));
console.log('PASS: compiled face exports, source transcription, negative score, missing-cost distinction, partial-text progress, base filtering and tamper rejection');
assert.equal(core.getFacilityIconMeaning, facilities.getFacilityIconMeaning);
assert.equal(core.getFacilityEffectText, facilities.getFacilityEffectText);
assert.equal(facilities.FOUNDERS_FACILITY_FACES.schemaVersion, '2.0.0');
assert.equal(facilities.getFacilityIconMeaning('red-green-up-down-cube').meaning, 'replace-influence');
assert.equal(facilities.getFacilityIconMeaning('blue-right-cube').label, '移动1个影响力');
assert.equal(facilities.getFacilityEffectText('FAC-003'), '入场；〔替换1个影响力〕 或 〔移除1个影响力〕');
assert.equal(facilities.getFacilityEffectText('FAC-CORE-COMMAND-TOWER'), '设置玩家面板时，放置在设施面板的初始位置上。');
assert.equal(facilities.getFacilityFaceTranscriptionProgress().flavor.transcribed, 18);
assert.equal(facilities.getFacilityFaceTranscriptionProgress().effects.transcribed, 18);
assert.equal(facilities.getFacilityFaceTranscriptionProgress().flavor.partial, 0);
assert.equal(facilities.FOUNDERS_FACILITY_FACES.facilities.every(row => row.flavor.verificationStatus === 'user-provided'), true);
assert.throws(() => facilities.getFacilityIconMeaning('constructor'), RangeError);
console.log('PASS: semantic symbols, corrected replacement, single move, 18 user flavor texts, both supplied full instructions and field provenance');
